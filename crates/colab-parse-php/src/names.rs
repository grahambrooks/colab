/// `text` (lower-cased) as an anonymous kind's name, if it is one.
pub(crate) fn anonymous(text: &str) -> Option<&'static str> {
    ANONYMOUS
        .iter()
        .copied()
        .find(|a| a.eq_ignore_ascii_case(text))
}
