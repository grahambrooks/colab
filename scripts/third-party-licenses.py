#!/usr/bin/env python3
"""Generate THIRD-PARTY-LICENSES.txt: the license of every crate the colab
binary is built from, on any release target, with the license texts the
crates ship.

A release archive holds only the binary, so the binary carries this file
(`colab licenses` prints it). Regenerate it after changing dependencies:

    scripts/third-party-licenses.py            # rewrite the file
    scripts/third-party-licenses.py --check    # exit 1 when it is stale (CI)

Dependencies are read from `cargo metadata --locked` (every platform, so
the Windows-only crates are included), following normal and build edges
from colab-cli; dev-dependencies are not shipped and are left out.
Identical texts are printed once, with every crate that ships them. A
crate whose package ships no license file takes its text from
scripts/licenses/<crate>.txt, copied from the crate's repository; a new
such crate fails the script until that file is added.
"""

import json
import pathlib
import subprocess
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
OUT = ROOT / "THIRD-PARTY-LICENSES.txt"
ROOT_PACKAGE = "colab-cli"
LICENSE_PREFIXES = ("LICENSE", "LICENCE", "COPYING", "NOTICE", "UNLICENSE", "COPYRIGHT")
CLARIFIED = ROOT / "scripts" / "licenses"
RULE = "=" * 78


def metadata() -> dict:
    out = subprocess.run(
        ["cargo", "metadata", "--locked", "--format-version", "1"],
        cwd=ROOT, check=True, capture_output=True, text=True,
    ).stdout
    return json.loads(out)


def shipped(meta: dict) -> list[dict]:
    """The third-party packages reachable from ROOT_PACKAGE without a dev edge."""
    packages = {p["id"]: p for p in meta["packages"]}
    nodes = {n["id"]: n for n in meta["resolve"]["nodes"]}
    root = next(p["id"] for p in meta["packages"]
                if p["name"] == ROOT_PACKAGE and p["source"] is None)
    seen, todo = set(), [root]
    while todo:
        node = nodes[todo.pop()]
        for dep in node["deps"]:
            kinds = {k["kind"] for k in dep["dep_kinds"]}
            if kinds <= {"dev"} or dep["pkg"] in seen:
                continue
            seen.add(dep["pkg"])
            todo.append(dep["pkg"])
    third = [packages[i] for i in seen if packages[i]["source"] is not None]
    return sorted(third, key=lambda p: (p["name"], p["version"]))


def license_files(package: dict) -> list[pathlib.Path]:
    folder = pathlib.Path(package["manifest_path"]).parent
    files = [f for f in folder.iterdir()
             if f.is_file() and f.name.upper().startswith(LICENSE_PREFIXES)]
    if package.get("license_file"):
        named = folder / package["license_file"]
        if named.is_file() and named not in files:
            files.append(named)
    return sorted(files, key=lambda f: f.name)


def render(packages: list[dict]) -> str:
    texts: dict[str, list[str]] = {}  # text -> "crate version (file)"
    missing: list[str] = []
    lines = [
        "Third-party licenses",
        "",
        "colab is MIT licensed (see LICENSE). The colab binary is built from the",
        "crates below; each is used under the license it declares, and the license",
        "texts the crates ship follow the list. None is modified, and the source",
        "of each is published at https://crates.io/crates/<name>/<version>. This",
        "file is generated by scripts/third-party-licenses.py; `colab licenses`",
        "prints it.",
        "",
        RULE,
        "",
    ]
    width = max(len(f"{p['name']} {p['version']}") for p in packages)
    for p in packages:
        name = f"{p['name']} {p['version']}"
        lines.append(f"{name:<{width}}  {p['license'] or '(no license declared)'}")
        files = [(f, f.name) for f in license_files(p)]
        if not files:
            clarified = CLARIFIED / f"{p['name']}.txt"
            if not clarified.is_file():
                missing.append(f"{name} ({p.get('repository') or 'no repository'})")
                continue
            files = [(clarified, f"none in the package; from {p['repository']}")]
        for f, label in files:
            text = f.read_text(encoding="utf-8", errors="replace").strip("\n")
            texts.setdefault(text, []).append(f"{name} ({label})")
    if missing:
        sys.exit("no license file in these packages; add its text as "
                 f"{CLARIFIED.relative_to(ROOT)}/<crate>.txt:\n  " + "\n  ".join(missing))
    for text, users in texts.items():
        lines += ["", RULE, ""]
        lines += [f"Shipped by {u}" for u in users]
        lines += ["", text]
    return "\n".join(lines) + "\n"


def main() -> int:
    text = render(shipped(metadata()))
    if sys.argv[1:] == ["--check"]:
        have = OUT.read_text(encoding="utf-8") if OUT.exists() else ""
        if have != text:
            print(f"{OUT.name} is out of date; run scripts/third-party-licenses.py",
                  file=sys.stderr)
            return 1
        return 0
    if sys.argv[1:]:
        print(__doc__, file=sys.stderr)
        return 2
    OUT.write_text(text, encoding="utf-8")
    return 0


if __name__ == "__main__":
    sys.exit(main())
